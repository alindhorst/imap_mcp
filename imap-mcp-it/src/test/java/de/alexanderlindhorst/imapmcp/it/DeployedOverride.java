package de.alexanderlindhorst.imapmcp.it;

/**
 * The test-only compose override of the deployed stack (SPEC 5.8). Allowlisted keys only: the backend network
 * internal with IPv6 off, no published ports on app and caddy, the app from the built image (no build, no pull),
 * healthcheck timing, and the added service {@code proxy}. It never touches ipam, environment, volumes or a
 * healthcheck test of a shipped service.
 */
final class DeployedOverride {

    private DeployedOverride() {
    }

    static String render(String appImage, String proxyImage) {
        return """
                # generated by the deployed-stack fixture; test only
                services:
                  postgres:
                    healthcheck:
                      interval: 3s
                  keycloak:
                    healthcheck:
                      interval: 3s
                  app:
                    image: %s
                    pull_policy: never
                    build: !reset null
                    ports: !reset []
                    healthcheck:
                      interval: 3s
                  caddy:
                    ports: !reset []
                  proxy:
                    image: %s
                    pull_policy: never
                    volumes:
                      - ./squid.conf:/etc/squid/squid.conf:ro,Z
                    ports:
                      - "127.0.0.1::3128"
                    depends_on:
                      app:
                        condition: service_healthy
                      caddy:
                        condition: service_started
                    networks: [backend, outside]
                networks:
                  backend:
                    internal: true
                    enable_ipv6: false
                  outside: {}
                """.formatted(appImage, proxyImage);
    }
}
